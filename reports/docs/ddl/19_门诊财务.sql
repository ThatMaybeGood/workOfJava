-- 索引（同样由 18 迁入，必须在本文件的 CREATE TABLE 之后执行）
-- CLINIC_MASTER / MOP_QUEUE 的过滤列(STAT_DATE)与关联列(STAT_DATE,VISIT_NO,APPOINTS_INDICATOR)均为主键前缀，由主键索引覆盖，不再单独建
CREATE INDEX IDX_FIN_RCPT_STAT ON TR_OUTP_FIN_RCPT_ACCT(STAT_DATE);
CREATE INDEX IDX_FIN_RCPT_PID_RCPT ON TR_OUTP_FIN_RCPT_ACCT(PATIENT_ID, RCPT_NO);
CREATE INDEX IDX_FIN_ACCT_STAT ON TR_OUTP_FIN_ACCT_MASTER(STAT_DATE);
CREATE INDEX IDX_FIN_ACCT_NO ON TR_OUTP_FIN_ACCT_MASTER(ACCT_NO);
CREATE INDEX IDX_FIN_PAY_RCPT ON TR_OUTP_FIN_PAYMENTS_MONEY(RCPT_NO);
CREATE INDEX IDX_FIN_PAY_MONEY_TYPE ON TR_OUTP_FIN_PAYMENTS_MONEY(MONEY_TYPE);
CREATE INDEX IDX_FIN_ACCT_MONEY_NO ON TR_OUTP_FIN_ACCT_MONEY(ACCT_NO);
-- 退项查询(T3)按 RETURNED_DATE 过滤, 主键索引(前导列STAT_DATE)用不上, 无索引导致全表扫描 68s 超 socket read timeout
CREATE INDEX IDX_FIN_CLINIC_RET ON TR_OUTP_FIN_CLINIC_MASTER(RETURNED_DATE, IS_RETURN_TYPE, APPOINTS_INDICATOR);

-- 7. TR_OUTP_FIN_VISIT_DAY - 人次日汇总（同患者+同日+同前缀+票号连续=一人次，按日预聚合；VisitDaySummaryTask 滚动维护）
CREATE TABLE TR_OUTP_FIN_VISIT_DAY (
    STAT_DATE   DATE NOT NULL,
    OPERATOR_NO VARCHAR2(20) DEFAULT '-',
    CNT_ALL     NUMBER(10),
    CNT_IN      NUMBER(10),
    CNT_REFUND  NUMBER(10),
    UPDATE_TIME DATE DEFAULT SYSDATE,
    CONSTRAINT PK_FIN_VISIT_DAY PRIMARY KEY (STAT_DATE, OPERATOR_NO)
);
COMMENT ON TABLE TR_OUTP_FIN_VISIT_DAY IS '门诊财务报表-人次日汇总(明细/柱图/bt4全部读此表毫秒级; 当天查询侧UNION实时算)';
COMMENT ON COLUMN TR_OUTP_FIN_VISIT_DAY.STAT_DATE IS '统计日(不含当天, 当天数据未抽完; 重算某日=DELETE该日+重插)';
COMMENT ON COLUMN TR_OUTP_FIN_VISIT_DAY.OPERATOR_NO IS '操作员号(NULL存-; bt4渠道DECODE分类)';
COMMENT ON COLUMN TR_OUTP_FIN_VISIT_DAY.CNT_ALL IS '人次-全量口径(T1小计/bt4)';
COMMENT ON COLUMN TR_OUTP_FIN_VISIT_DAY.CNT_IN IS '人次-进项口径(T2; 先过滤TOTAL_CHARGES>=0再合并, 与实时算法等价)';
COMMENT ON COLUMN TR_OUTP_FIN_VISIT_DAY.CNT_REFUND IS '人次-退项口径(T3; 先过滤退费红冲行再合并)';
