-- 1. TR_OUTP_FIN_CLINIC_MASTER - 门诊挂号明细（← clinic_master）
CREATE TABLE TR_OUTP_FIN_CLINIC_MASTER (
    STAT_DATE            DATE NOT NULL,
    PATIENT_ID           VARCHAR2(50),
    VISIT_DATE           DATE NOT NULL,
    RETURNED_DATE        DATE,
    IS_RETURN_TYPE       NUMBER(1),
    CLINIC_LABEL         VARCHAR2(100),
    VISIT_TIME_DESC      VARCHAR2(100),
    OPERATOR_NO          VARCHAR2(20),
    REGIST_FEE           NUMBER(18,4),
    CLINIC_FEE           NUMBER(18,4),
    CREATE_TIME          DATE DEFAULT SYSDATE,
    UPDATE_TIME          DATE DEFAULT SYSDATE,
    ETL_SRC              VARCHAR2(100),
    ETL_BATCH_NO         VARCHAR2(50),
    SOURCE_TYPE          VARCHAR2(20),
    REGISTRATION_STATUS  NUMBER(1),
    RETURNED_OPERATOR    VARCHAR2(20),
    RETURNED_OPERATOR_NO VARCHAR2(8),
    QUEUE_TYPE           VARCHAR2(10),
    REGISTERING_DATE     DATE,
    APPOINTS_INDICATOR   NUMBER(1) NOT NULL,
    VISIT_NO             NUMBER(18) NOT NULL,
    PATIENT_NAME         VARCHAR2(20),
    ID_NO                VARCHAR2(18),
    QUEUE_NUM            NUMBER,
    DEPT_CODE            VARCHAR2(100),
    CONSTRAINT PK_CLINIC_MASTER PRIMARY KEY (STAT_DATE, VISIT_NO, APPOINTS_INDICATOR)
);
-- 2. TR_OUTP_FIN_RCPT_ACCT - 门诊收据明细（← outp_rcpt_master）
CREATE TABLE TR_OUTP_FIN_RCPT_ACCT (
    RCPT_NO             VARCHAR2(64) NOT NULL,
    PATIENT_ID          VARCHAR2(64),
    STAT_DATE           DATE,
    VISIT_DATE          DATE,
    TOTAL_CHARGES       NUMBER(18,2),
    TOTAL_COSTS         NUMBER(18,2),
    REFUNDED_RCPT_NO    VARCHAR2(64),
    OPERATOR_NO         VARCHAR2(20),
    BILL_CLASS          VARCHAR2(10),
    CREATE_TIME         DATE DEFAULT SYSDATE,
    UPDATE_TIME         DATE DEFAULT SYSDATE
);
-- 3. TR_OUTP_FIN_ACCT_MASTER - 门诊结账汇总（← outp_acct_master，收据张数/金额唯一口径）
CREATE TABLE TR_OUTP_FIN_ACCT_MASTER (
    ACCT_NO             VARCHAR2(64),
    ACCT_DATE           DATE,
    STAT_DATE           DATE,
    OPERATOR_NO         VARCHAR2(20),
    TOTAL_COSTS         NUMBER(18,2),
    TOTAL_INCOMES       NUMBER(18,2),
    REFUND_AMOUNT       NUMBER(18,2),
    RCPTS_NUM           NUMBER(12),
    REFUND_NUM          NUMBER(12),
    FREE_OF_CHARGE_NUM  NUMBER(12),
    CREATE_TIME         DATE DEFAULT SYSDATE,
    UPDATE_TIME         DATE DEFAULT SYSDATE
);
-- 4. TR_OUTP_FIN_PAYMENTS_MONEY - 门诊支付明细（← outp_payments_money，无日期列需JOIN补）
CREATE TABLE TR_OUTP_FIN_PAYMENTS_MONEY (
    RCPT_NO             VARCHAR2(64) NOT NULL,
    MONEY_TYPE          VARCHAR2(30),
    PAYMENT_AMOUNT      NUMBER(18,2),
    REFUNDED_AMOUNT     NUMBER(18,2),
    CREATE_TIME         DATE DEFAULT SYSDATE,
    UPDATE_TIME         DATE DEFAULT SYSDATE
);
-- 5. TR_OUTP_FIN_MOP_QUEUE - 排班队列（← cq_card.mop_timeschedule_queue）
CREATE TABLE TR_OUTP_FIN_MOP_QUEUE (
    STAT_DATE          DATE NOT NULL,
    SCHEDULE_ID        VARCHAR2(200),
    PATIENT_ID         VARCHAR2(50),
    QUEUE_TYPE         VARCHAR2(20),
    IS_USED            VARCHAR2(20),
    VISIT_SOURCE       VARCHAR2(50),
    OPERATOR_NO        VARCHAR2(20),
    RETURNED_DATE      DATE,
    CLINIC_LABEL       VARCHAR2(100),
    VISIT_DATE         DATE,
    VISIT_TIME_DESC    VARCHAR2(100),
    CREATE_TIME        DATE DEFAULT SYSDATE,
    UPDATE_TIME        DATE DEFAULT SYSDATE,
    ETL_SRC            VARCHAR2(100),
    ETL_BATCH_NO       VARCHAR2(50),
    QUEUE_NUM          NUMBER,
    VISIT_NO           NUMBER(10) NOT NULL,
    SOURCE_NAME        VARCHAR2(40),
    SOURCE_TYPE        VARCHAR2(2),
    APPOINTS_INDICATOR NUMBER(1) NOT NULL,
    ID_NO              NUMBER(18),
    CONSTRAINT PK_MOP_QUEUE PRIMARY KEY (STAT_DATE, APPOINTS_INDICATOR, VISIT_NO)
);
